def check_diag(diag: dict[str, Any], flagged: list[tuple[Key, dict[str, Any], list[str]]]) -> dict[Key, dict[str, Any]]:
    dg = {_key(x): x for x in diag["groups"]}
    _assert(len(dg) == len(diag["groups"]), "診斷 groups 有重複組鍵")
    _assert(set(dg) == {k for k, _, _ in flagged}, "診斷的組與 stats 報告的須解釋組不一致")
    for k, g, reasons in flagged:
        d = dg[k]
        _need(d, ("reasons", "registry", "population", "n_sampled", "patterns", "boundary_rows", "mode_rows", "conclusion"),
              f"診斷 {_kname(k)}")
        _assert(list(d["reasons"]) == reasons, f"{_kname(k)}：診斷的理由 {d['reasons']} ≠ stats {reasons}")
        _assert(d["registry"] == g["registry"], f"{_kname(k)}：診斷的登錄區間 ≠ stats")
        pp = d["population"]
        _assert(pp["n"] == g["n"], f"{_kname(k)}：診斷母體 {pp['n']} ≠ stats n {g['n']}")
        for f in ("share_at_boundary", "mode_value", "mode_share"):
            _assert(abs(pp[f] - g[f]) <= FIELD_TOL, f"{_kname(k)}：診斷 {f}={pp[f]!r} ≠ stats {g[f]!r}")
        _assert(abs(sum(p["est_share"] for p in d["patterns"]) - 1.0) <= SHARE_SUM_TOL,
                f"{_kname(k)}：族缺值型態的佔母體比例加總不是 1")
        _assert(sum(sum(p["n_sample"].values()) for p in d["patterns"]) == d["n_sampled"],
                f"{_kname(k)}：族缺值型態的抽樣筆數加總 ≠ n_sampled")
        for blk, has in (("boundary_rows", pp["n_boundary"] > 0), ("mode_rows", pp["n_mode"] > 0)):
            sigs = d[blk]["signatures"]
            _assert(bool(sigs) is has, f"{_kname(k)}：{blk} 的簽名有無與母體列數不一致")
            if sigs:
                _assert(abs(sum(s["share"] for s in sigs) - 1.0) <= SHARE_SUM_TOL, f"{_kname(k)}：{blk} 簽名比例加總不是 1")
    par = diag["parity"]
    _need(par, ("rows", "max_abs_diff", "tol"), "診斷 parity")
    n_s = sum(x["n_sampled"] for x in diag["groups"])
    _assert(par["rows"] == n_s and n_s > 0, f"parity 列數 {par['rows']} ≠ 各組抽樣列數加總 {n_s}（或為 0）")
    _assert(par["tol"] <= PARITY_TOL_MAX, f"parity 容差 {par['tol']} 寬於 {PARITY_TOL_MAX}")
    _assert(par["max_abs_diff"] <= par["tol"], f"parity 最大差 {par['max_abs_diff']} 超過容差 {par['tol']}——診斷不可信")
    return dg


