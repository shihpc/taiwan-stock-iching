def build(rep: dict[str, Any], diag: dict[str, Any], report_path: Path, diag_path: Path) -> str:
    check_inputs(rep, diag, report_path)
    check_counts(rep)
    lo, hi, esc = check_712(rep)
    unobs = check_714(rep)
    flagged = check_716(rep)
    check_confirmed([k for k, _, _ in flagged])
    dg = check_diag(diag, flagged)
    s, sm, rows = rep["sample"], rep["summary"], rep["sample"]["rows"]
    obs = [x for x in rep["groups"] if x["n"]]
    mv = rep["registry_model_versions"]
    n_rows = sum(rows.values())
    L = ["## 附錄 C：§16.5 `:712`／`:714` 步驟 4／`:716` 實測結果（裁定 #64／#65／#66）", "",
         "**本節由 `scripts/stats_appendix.py` 從下列兩份報告生成，不得手改**（重跑會整段覆寫）。", "",
         "### 報告來源與綁定", "",
         "| 項目 | 值 |", "|---|---|",
         f"| stats 報告（`scripts/score_stats.py`） | `{_disp(report_path)}`（sha256 `{_sha256(report_path)}`） |",
         f"| 族組成診斷（`scripts/score_diag716.py`） | `{_disp(diag_path)}`（sha256 `{_sha256(diag_path)}`） |",
         f"| `data_version` | `{rep['data_version']}`（兩份相同） |",
         f"| `params_sha` | `{rep['params_sha']}`（兩份相同） |",
         f"| 登錄檔的 `model_version` | twse `{mv['twse']}`／tpex `{mv['tpex']}` |",
         f"| 樣本段（裁定 #64 ①） | {s['start']}～{s['end']}；落地 {s['n_days']:,} 日（{s['first_day']}～{s['last_day']}） |",
         f"| 列數 | 個股池內 {rows['stock_in_pool']:,}＋池外 {rows['stock_out_pool']:,}＋大盤 {rows['market_index']:,}"
         f"＝{n_rows:,} 列（×6 爻＝{LINES_PER_ROW * n_rows:,} 個爻值；其中未知爻 "
         f"{sum(u['n'] for u in rep['unknown']):,} 個不進統計） |", "",
         "兩份報告的 `data_version`／`params_sha`／樣本段相同、診斷讀的就是這份 stats 報告、"
         "須解釋組的母體數字（n、達邊界比例、最常出現值與其佔比、登錄區間）兩邊一致，本附錄才產出。"
         f"全文表（{len(rep['groups'])} 組，含五數、偏態、[45, 55] 比例）不貼入，見上列報告檔（同名 `.txt` 為同次產出的文字版）。", ""]

    # ---- :712 ----
    L += ["### `:712` 合法範圍", "",
          f"- 所有爻分數須落在 [{RANGE_712[0]:.2f}, {RANGE_712[1]:.2f}]（容許 ±{TOL}）：{len(obs)} 個有觀測組、"
          f"{sum(x['n'] for x in obs):,} 個爻值，逸出 **{esc}** 筆 → **PASS**（實測）。"
          f"全體最小值 {lo:.6f}、最大值 {hi:.6f}。",
          "- 同一行的後半「`N` 只套一次、`P_cs` 不套」不在 db 報告內（`scores.db` 不存子指標層），"
          "由 `tests/test_n_once.py` 驗（`docs/P3-CALIBRATION.md` §26）。", ""]

    # ---- :714 ----
    by_sc = Counter((x["scope"], x["coverage"]) for x in unobs)
    lines_sc: dict[tuple[str, str], set[str]] = {}
    for x in unobs:
        lines_sc.setdefault((x["scope"], x["coverage"]), set()).add(str(x["line"]))
    L += ["### `:714` 步驟 4：實測極值 vs 可達邊界登錄（`docs/score-ranges.md`）", "",
          f"- {sm['groups_observed']}／{sm['groups_total']} 組有觀測，越界 **{len(sm['violations_714'])}** 組 → **PASS**"
          f"（實測；容許 ±{TOL}，甲比甲、乙比乙）。",
          f"- 未觀測的 {len(unobs)} 組（樣本段內該爻從未以此 coverage 出現，n＝0）依 scope×coverage："]
    for (sc, cov), n in sorted(by_sc.items()):
        L.append(f"  - `{sc}`／`{cov}`：{n} 組（爻 {'、'.join(sorted(lines_sc[(sc, cov)]))}）")
    L.append("")

    # ---- :716 ----
    L += ["### `:716` 分布檢查", "",
          f"門檻（嚴格不等式）：達邊界比例 > {_p(BOUNDARY_SHARE_MAX)}、相異值數 < {DISTINCT_MIN}（規格 `:716`）；"
          f"單一值佔比 > {_p(MODE_SHARE_MAX)}（裁定 #65 ①：四捨五入到小數 {MODE_DECIMALS} 位後最常出現值的佔比）。"
          f"「達邊界」＝距登錄端點 ≤ {TOL}。{len(obs)} 個有觀測組中須解釋 **{len(flagged)}** 組：", "",
          "| 組 | n | 達邊界比例 | 相異值數 | 單一值佔比 @ 值 | 須解釋的理由 | 裁定 |",
          "|---|---:|---:|---:|---|---|---|"]
    for k, g, reasons in flagged:
        L.append(f"| {_kname(k)} | {g['n']:,} | {_p(g['share_at_boundary'])} | {g['distinct']:,} | "
                 f"{_p(g['mode_share'])} @ {g['mode_value']:.6f} | {'、'.join(reasons)} | {_status(k)} |")
