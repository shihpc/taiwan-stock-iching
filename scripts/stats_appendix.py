def _explain_single_sub(k: Key, g: dict, d: dict) -> list[str]:
    _assert(k[3] == "1" and k[2] in ("short", "swing") and k[4] == "reweighted",
            f"{_kname(k)}：「族 A 只剩一個子指標」的說明只適用於短線／波段個股初爻 reweighted")
    pats = d["patterns"]
    _assert(len(pats) == 1 and pats[0]["pattern"] == "A 在場" and abs(pats[0]["est_share"] - 1.0) <= SHARE_SUM_TOL,
            f"{_kname(k)}：族缺值型態不是 100% 的『A 在場』")
    endpoint_share = 0.0
    n_sig = 0
    for blk in ("boundary_rows", "mode_rows"):
        for s in d[blk]["signatures"]:
            fams = parse_signature(s["key"])
            _assert(len(fams) == 1 and fams[0][0] == "A" and isinstance(fams[0][1], list),
                    f"{_kname(k)}：簽名 {s['key']!r} 不是只有族 A")
            subs = fams[0][1]
            present = [(i, st) for i, st in subs if not st.startswith("缺:")]
            _assert(len(subs) == 2 and len(present) == 1 and present[0][1] in ENDPOINT_STATUS,
                    f"{_kname(k)}：簽名 {s['key']!r} 不是「一個缺、另一個在 S 端點」")
            if blk == "boundary_rows":
                n_sig += 1
                if present[0][1].startswith("端點"):
                    endpoint_share += s["share"]
    reg, mv = g["registry"], g["mode_value"]
    near = [i for i, e in enumerate(reg) if abs(mv - e) <= TOL]
    _assert(len(near) == 1, f"{_kname(k)}：最常出現值 {mv} 不在登錄區間任一端點 ±{TOL} 內")
    _assert(abs(reg[0] - RANGE_712[0]) <= TOL and abs(reg[1] - RANGE_712[1]) <= TOL,
            f"{_kname(k)}：登錄區間 {reg} 不是 S 全幅，「子指標在 S 端點 ⇒ 爻分數在登錄端點」不成立")
    _assert(d["strata"]["mode"]["population"] == 0, f"{_kname(k)}：有單一值列不是達邊界列（診斷 M 層非空）")
    end = "上界" if near[0] == 1 else "下界"
    return [
        f"- 族缺值型態 {_p(pats[0]['est_share'])} 為『A 在場』（實測）。短線／波段個股初爻的族權重只有族 A"
        "（程式現況：`src/iching/score/params.py` 的 `build_params` 設 `FW[(sc, h, \"1\")] = {\"A\": 1.0}`；"
        "不是本報告量測的數字）。",
        "- 本組為 reweighted＝族 A 的兩個子指標（`revenue_yoy`、`revenue_accel`）缺一個；族分數與爻分數都是加權平均"
        "（`src/iching/score/aggregate.py` 的 `family_score`／`line_score`），所以爻分數＝剩下那一個子指標的 S 值"
        "（由定義推得）。該子指標落在 S 端點時，爻分數就在登錄端點。",
        f"- 邊界列的子指標簽名 {n_sig} 種、單一值列的簽名，**全部**是「一個缺、另一個在 S 端點」（實測）；"
        f"邊界列中 clip 生效佔 {_p(1.0 - endpoint_share)}、未 clip 但子指標分數距 S 端點 ≤ {TOL} 佔 {_p(endpoint_share)}（加權估計）。",
        f"- 最常出現值 {mv:.6f} 即登錄{end}（實測，距端點 ≤ {TOL}），且單一值列全部也是達邊界列"
        "（診斷分層「只是單一值」層母體 0 列，實測）。",
    ]


def _explain_equal_subs(k: Key, g: dict, d: dict) -> list[str]:
    _assert(d["reasons"] == [R_MODE], f"{_kname(k)}：「在場子指標皆等於最常出現值」只說明單一值，本組還有其他理由")
    mv = round(g["mode_value"], 4)
    sigs = d["mode_rows"]["signatures"]
    for s in sigs:
        fams = parse_signature(s["key"])
        vals = [st for _, subs in fams if isinstance(subs, list) for _, st in subs]
        _assert(bool(vals) and all(st.startswith("=") and float(st[1:]) == mv for st in vals),
                f"{_kname(k)}：單一值列簽名 {s['key']!r} 的在場子指標不全等於 {mv}")
        _assert(any(isinstance(subs, str) for _, subs in fams), f"{_kname(k)}：簽名 {s['key']!r} 沒有缺席的族（不是 reweighted）")
    top = sigs[0]
    return [
        f"- 最常出現值 {g['mode_value']:.6f} 的列中 {_p(top['share'])} 為『{top['key']}』（實測）。",
        f"- 單一值列的子指標簽名 {len(sigs)} 種，**全部**是「在場子指標的值都等於 {mv:.4f}、至少一族缺席」（實測）；"
        "族分數與爻分數都是加權平均（`src/iching/score/aggregate.py` 的 `family_score`／`line_score`），"
        f"權重怎麼重配都得 {mv:.4f}（由定義推得）。",
        "- 子指標為什麼取這個值（情境表的哪一格、原始量是多少）：**未量測**。",
    ]


def _explain_fixed_pos(k: Key, g: dict, d: dict) -> list[str]:
    _assert(d["reasons"] == [R_MODE], f"{_kname(k)}：「截斷位置固定」只說明單一值，本組還有其他理由")
    sigs = d["mode_rows"]["signatures"]
    _assert(len(sigs) == 1, f"{_kname(k)}：單一值列不只一種簽名，「在場族與子指標相同」不成立")
    subs = d["mode_rows"]["subs"]
    _assert(bool(subs), f"{_kname(k)}：單一值列沒有在場子指標")
    for sid, e in subs.items():
        _assert(e["u_min"] is not None and e["u_min"] == e["u_max"], f"{_kname(k)}：{sid} 的 u 在單一值列上不固定")
        _assert(isinstance(e["c"], list) and len(e["c"]) == 1 and isinstance(e["d"], list) and len(e["d"]) == 1,
                f"{_kname(k)}：{sid} 的 c／d 不是單一值")
    by_u: dict[float, list[str]] = {}
    for sid, e in subs.items():
        by_u.setdefault(e["u_min"], []).append(f"`{sid.split('.', 1)[1]}`")
    ns = sorted({e["n_sample"] for e in subs.values()})
    pos = "；".join(f"u＝{u:g}".replace("-", "−") + f"：{'、'.join(ids)}" for u, ids in sorted(by_u.items(), key=lambda t: -t[0]))
    missing = [f"{f} {why}" for f, why in parse_signature(sigs[0]["key"]) if isinstance(why, str)]
    return [
        f"- 最常出現值 {g['mode_value']:.6f} 的列只有一種子指標簽名（{_p(sigs[0]['share'])}，實測）："
        f"『{sigs[0]['key']}』。",
        f"- 這些列上在場子指標的截斷位置 u 全部固定、c／d 各為單一值（實測，抽 {'／'.join(f'{n:,}' for n in ns)} 列）：{pos}。"
        f"缺席的族：{'、'.join(missing) if missing else '無'}。",
        "- 在場族與子指標相同、各子指標 x 相同 ⇒ 子指標分數相同 ⇒ 加權平均相同（由定義推得）。"
        + "".join(t for u, t in ((0.0, "u＝0 即 x＝c；"), (1.0, "|u|＝1 即 x 恰在截斷端點 c±3d；"))
                  if any(abs(v) == u for v in by_u))
        + "定義見診斷報告 `u_definition`。",
        "- x 為什麼恰落在這些位置（原始量是多少）：**未量測**。",
    ]


EXPLAINERS = {"single_sub": _explain_single_sub, "equal_subs": _explain_equal_subs, "fixed_pos": _explain_fixed_pos}


def _status(k: Key) -> str:
    c = CONFIRMED.get(k)
    return f"已確認為預期行為（{c}）" if c else "待使用者確認（凍結前必須補齊）"


