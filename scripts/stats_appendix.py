# ---------------------------------------------------------------------------
# 子指標簽名解析（`score_diag716` 的簽名格式：族以「；」分隔，族內「X{id 狀態｜…}」或「X 缺:原因」）
# ---------------------------------------------------------------------------
_FAM_PRESENT = re.compile(r"^([A-Z])\{(.*)\}$")
_FAM_MISSING = re.compile(r"^([A-Z]) 缺:(\S+)$")


def parse_signature(sig: str) -> list[tuple[str, list[tuple[str, str]] | str]]:
    """回 [(族, [(子指標, 狀態), …])｜(族, "缺:原因")]。子指標狀態：`clip↑`／`端點↓(未clip)`／`=50.0000`／`缺:missing`…"""
    out: list[tuple[str, list[tuple[str, str]] | str]] = []
    for part in sig.split("；"):
        m = _FAM_MISSING.match(part)
        if m:
            out.append((m.group(1), f"缺:{m.group(2)}"))
            continue
        m = _FAM_PRESENT.match(part)
        _assert(m is not None, f"子指標簽名無法解析：{sig!r}")
        subs = []
        for s in m.group(2).split("｜"):
            if "=" in s and " " not in s:
                sid, val = s.split("=", 1)
                subs.append((sid, f"={val}"))
            else:
                sid, _, st = s.partition(" ")
                _assert(bool(st), f"子指標簽名無法解析：{sig!r}")
                subs.append((sid, st))
        out.append((m.group(1), subs))
    return out


